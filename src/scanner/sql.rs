#[cfg(test)]
mod tests {
    use super::SQL;
    use crate::{scanner::ground, syntax::SyntaxClass};

    #[test]
    fn classifies_a_sample_line() {
        assert_eq!(
            ground(
                &SQL,
                "SELECT u.id, COUNT(*) AS total FROM users u WHERE u.active = TRUE AND u.age >= 18 -- adults"
            ),
            [
                ("SELECT", SyntaxClass::Keyword),
                ("COUNT", SyntaxClass::Function),
                ("*", SyntaxClass::Operator),
                ("AS", SyntaxClass::Keyword),
                ("FROM", SyntaxClass::Keyword),
                ("users", SyntaxClass::Type),
                ("WHERE", SyntaxClass::Keyword),
                ("=", SyntaxClass::Operator),
                ("TRUE", SyntaxClass::Constant),
                ("AND", SyntaxClass::Keyword),
                (">=", SyntaxClass::Operator),
                ("18", SyntaxClass::Number),
                ("-- adults", SyntaxClass::Comment),
            ]
        );
    }
}
