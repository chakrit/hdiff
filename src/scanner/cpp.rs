//! C++'s lexical pieces. A preprocessor directive is the word after `#`; raw strings are
//! recognized only with an empty delimiter, as `R"(...)"`.

use super::{Marker, Pair, Spec, WordBytes, WordCase};
use crate::syntax::SyntaxClass;

pub static CPP: Spec = Spec {
    line_markers: &[Marker::anywhere("//", SyntaxClass::Comment)],
    delimited: &[
        Pair::spanning("/*", "*/", SyntaxClass::Comment),
        Pair::spanning("R\"(", ")\"", SyntaxClass::String),
        Pair::escaped("\"", SyntaxClass::String),
        Pair::character("'", SyntaxClass::Number),
    ],
    word_bytes: WordBytes::with(b""),
    words: &[
        (
            &[
                "alignas",
                "alignof",
                "break",
                "case",
                "catch",
                "class",
                "co_await",
                "co_return",
                "co_yield",
                "concept",
                "const",
                "consteval",
                "constexpr",
                "constinit",
                "continue",
                "decltype",
                "default",
                "delete",
                "do",
                "else",
                "enum",
                "explicit",
                "extern",
                "final",
                "for",
                "friend",
                "goto",
                "if",
                "inline",
                "mutable",
                "namespace",
                "new",
                "noexcept",
                "operator",
                "override",
                "private",
                "protected",
                "public",
                "requires",
                "return",
                "sizeof",
                "static",
                "static_assert",
                "struct",
                "switch",
                "template",
                "thread_local",
                "throw",
                "try",
                "typedef",
                "typename",
                "union",
                "using",
                "virtual",
                "volatile",
                "while",
            ],
            SyntaxClass::Keyword,
        ),
        (
            &[
                "auto",
                "bool",
                "char",
                "char16_t",
                "char32_t",
                "char8_t",
                "double",
                "float",
                "int",
                "int16_t",
                "int32_t",
                "int64_t",
                "int8_t",
                "intptr_t",
                "long",
                "ptrdiff_t",
                "short",
                "signed",
                "size_t",
                "ssize_t",
                "uint16_t",
                "uint32_t",
                "uint64_t",
                "uint8_t",
                "uintptr_t",
                "unsigned",
                "void",
                "wchar_t",
            ],
            SyntaxClass::Type,
        ),
        (&["NULL", "false", "nullptr", "true"], SyntaxClass::Constant),
    ],
    before: &[("(", SyntaxClass::Function)],
    after: &[
        ("#", SyntaxClass::Keyword),
        (".", SyntaxClass::Property),
        ("->", SyntaxClass::Property),
        ("enum", SyntaxClass::Type),
        ("struct", SyntaxClass::Type),
        ("union", SyntaxClass::Type),
        ("class", SyntaxClass::Type),
    ],
    upper_case: Some(SyntaxClass::Constant),
    capitalized: None,
    other_words: Some(SyntaxClass::Variable),
    word_suffixes: b"",
    word_case: WordCase::Sensitive,
};

#[cfg(test)]
mod tests {
    use super::CPP;
    use crate::{scanner::ground, syntax::SyntaxClass};

    #[test]
    fn classifies_a_sample_line() {
        assert_eq!(
            ground(
                &CPP,
                r#"auto node = std::make_unique<Node>(42); if (node->next != nullptr) return R"(raw "text")"; // walk"#
            ),
            [
                ("auto", SyntaxClass::Type),
                ("node", SyntaxClass::Variable),
                ("=", SyntaxClass::Operator),
                ("std", SyntaxClass::Variable),
                ("::", SyntaxClass::Operator),
                ("make_unique", SyntaxClass::Variable),
                ("<", SyntaxClass::Operator),
                ("Node", SyntaxClass::Variable),
                (">", SyntaxClass::Operator),
                ("42", SyntaxClass::Number),
                ("if", SyntaxClass::Keyword),
                ("node", SyntaxClass::Variable),
                ("->", SyntaxClass::Operator),
                ("next", SyntaxClass::Property),
                ("!=", SyntaxClass::Operator),
                ("nullptr", SyntaxClass::Constant),
                ("return", SyntaxClass::Keyword),
                (r#"R"(raw "text")""#, SyntaxClass::String),
                ("// walk", SyntaxClass::Comment),
            ]
        );
    }
}
