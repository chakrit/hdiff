//! CUDA's lexical pieces. A preprocessor directive is the word after `#`; raw strings are
//! recognized only with an empty delimiter, as `R"(...)"`.

use super::{Marker, Pair, Spec, WordBytes, WordCase};
use crate::syntax::SyntaxClass;

pub static CUDA: Spec = Spec {
    line_markers: &[Marker::anywhere("//", SyntaxClass::Comment)],
    delimited: &[
        Pair::spanning("/*", "*/", SyntaxClass::Comment),
        Pair::spanning("R\"(", ")\"", SyntaxClass::String),
        Pair::escaped("\"", SyntaxClass::String),
        Pair::character("'", SyntaxClass::Number),
    ],
    word_bytes: WordBytes::with(b""),
    words: &[
        (
            &[
                "__constant__",
                "__device__",
                "__forceinline__",
                "__global__",
                "__host__",
                "__launch_bounds__",
                "__managed__",
                "__noinline__",
                "__restrict__",
                "__shared__",
                "alignas",
                "alignof",
                "break",
                "case",
                "catch",
                "class",
                "co_await",
                "co_return",
                "co_yield",
                "concept",
                "const",
                "consteval",
                "constexpr",
                "constinit",
                "continue",
                "decltype",
                "default",
                "delete",
                "do",
                "else",
                "enum",
                "explicit",
                "extern",
                "final",
                "for",
                "friend",
                "goto",
                "if",
                "inline",
                "mutable",
                "namespace",
                "new",
                "noexcept",
                "operator",
                "override",
                "private",
                "protected",
                "public",
                "requires",
                "return",
                "sizeof",
                "static",
                "static_assert",
                "struct",
                "switch",
                "template",
                "thread_local",
                "throw",
                "try",
                "typedef",
                "typename",
                "union",
                "using",
                "virtual",
                "volatile",
                "while",
            ],
            SyntaxClass::Keyword,
        ),
        (
            &[
                "auto",
                "bool",
                "char",
                "char16_t",
                "char32_t",
                "char8_t",
                "dim3",
                "double",
                "float",
                "int",
                "int16_t",
                "int32_t",
                "int64_t",
                "int8_t",
                "intptr_t",
                "long",
                "ptrdiff_t",
                "short",
                "signed",
                "size_t",
                "ssize_t",
                "uint16_t",
                "uint32_t",
                "uint64_t",
                "uint8_t",
                "uintptr_t",
                "unsigned",
                "void",
                "wchar_t",
            ],
            SyntaxClass::Type,
        ),
        (&["NULL", "false", "nullptr", "true"], SyntaxClass::Constant),
    ],
    before: &[("(", SyntaxClass::Function)],
    after: &[
        ("#", SyntaxClass::Keyword),
        (".", SyntaxClass::Property),
        ("->", SyntaxClass::Property),
        ("enum", SyntaxClass::Type),
        ("struct", SyntaxClass::Type),
        ("union", SyntaxClass::Type),
        ("class", SyntaxClass::Type),
    ],
    upper_case: Some(SyntaxClass::Constant),
    capitalized: None,
    other_words: Some(SyntaxClass::Variable),
    word_suffixes: b"",
    word_case: WordCase::Sensitive,
};

#[cfg(test)]
mod tests {
    use super::CUDA;
    use crate::{scanner::ground, syntax::SyntaxClass};

    #[test]
    fn classifies_a_sample_line() {
        assert_eq!(
            ground(
                &CUDA,
                "__global__ void scale(float* out, int n) { int i = blockIdx.x * blockDim.x + threadIdx.x; if (i < n) out[i] *= 2.0f; }"
            ),
            [
                ("__global__", SyntaxClass::Keyword),
                ("void", SyntaxClass::Type),
                ("scale", SyntaxClass::Function),
                ("float", SyntaxClass::Type),
                ("*", SyntaxClass::Operator),
                ("out", SyntaxClass::Variable),
                ("int", SyntaxClass::Type),
                ("n", SyntaxClass::Variable),
                ("int", SyntaxClass::Type),
                ("i", SyntaxClass::Variable),
                ("=", SyntaxClass::Operator),
                ("blockIdx", SyntaxClass::Variable),
                ("x", SyntaxClass::Property),
                ("*", SyntaxClass::Operator),
                ("blockDim", SyntaxClass::Variable),
                ("x", SyntaxClass::Property),
                ("+", SyntaxClass::Operator),
                ("threadIdx", SyntaxClass::Variable),
                ("x", SyntaxClass::Property),
                ("if", SyntaxClass::Keyword),
                ("i", SyntaxClass::Variable),
                ("<", SyntaxClass::Operator),
                ("n", SyntaxClass::Variable),
                ("out", SyntaxClass::Variable),
                ("i", SyntaxClass::Variable),
                ("*=", SyntaxClass::Operator),
                ("2.0f", SyntaxClass::Number),
            ]
        );
    }
}
