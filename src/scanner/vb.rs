#[cfg(test)]
mod tests {
    use super::VB;
    use crate::{scanner::ground, syntax::SyntaxClass};

    #[test]
    fn classifies_a_sample_line() {
        assert_eq!(
            ground(
                &VB,
                "Public Function Total(ByVal items As List(Of Integer)) As Integer : Return If(items Is Nothing, 0, items.Count) ' sum"
            ),
            [
                ("Public", SyntaxClass::Keyword),
                ("Function", SyntaxClass::Keyword),
                ("Total", SyntaxClass::Function),
                ("ByVal", SyntaxClass::Keyword),
                ("items", SyntaxClass::Variable),
                ("As", SyntaxClass::Keyword),
                ("List", SyntaxClass::Type),
                ("Of", SyntaxClass::Keyword),
                ("Integer", SyntaxClass::Type),
                ("As", SyntaxClass::Keyword),
                ("Integer", SyntaxClass::Type),
                ("Return", SyntaxClass::Keyword),
                ("If", SyntaxClass::Keyword),
                ("items", SyntaxClass::Variable),
                ("Is", SyntaxClass::Operator),
                ("Nothing", SyntaxClass::Constant),
                ("0", SyntaxClass::Number),
                ("items", SyntaxClass::Variable),
                ("Count", SyntaxClass::Property),
                ("' sum", SyntaxClass::Comment),
            ]
        );
    }
}
